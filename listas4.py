# Faça um programa com uma variável de idades e nela
# Guarde 6 índices, onde no código deve mostrar quais 
# idades são maior de idade (>=18) e menor de idade (>18)

idade = [3, 14, 19, 25, 1915, 1]

for i in idade:
  if i >= 18:
   print(i, "é maior de idade")
  else:
    print(i, "é menor de idade")